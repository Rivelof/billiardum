// Перепроверка M4-5 после исправления (код ef78f68): маска телефонов в отзывах и ответах клуба.
//
// Путь: POST /api/reviews {text} → server/directory/reviews.mjs upsert (~53–56: text() только обрезает
// пробелы, затем maskPhones) → bl.reviews.text → GET /api/clubs/{club}/reviews и страница клуба на сайте.
// Маска — server/notify/index.mjs NUMBER_RUN (~30): между цифрами допускается только перечень
// разделителей [\s./\\()\-‐-―+*_|].
//
// Выдержало: все записи из PoC M4-5 и обычные записи номера маскируются; даты, время и цены — нет.
// НАХОДКА M4-8 (низкая, данные гостей): невидимые символы (U+200B, U+00AD, U+2060) и читаемые
// разделители не из перечня (· , : ~ «...») проходят без маски — на странице клуба номер читается целиком.
//
// Запуск: node --test tests/security/m4/phone_mask_recheck.test.mjs   (без базы)

import assert from 'node:assert/strict';
import { test } from 'node:test';
import { maskPhones } from '../../../server/notify/index.mjs';

test('M4-5 выдержало: номера из PoC и обычные записи маскируются, даты и цены — нет', () => {
  for (const s of ['+7.912.345.67.81', '8/912/345/67/82', '8 (912) 345-67-83', '+7_912_345_67_84', '+7 912.345/67-85', '+7—912—345—67—87', '+7 912 345 67 05']) {
    assert.equal(maskPhones(`звоните ${s}`), 'звоните ***', s);
  }
  assert.equal(maskPhones('21.10.2026 в 21:30, 1 490 ₽'), '21.10.2026 в 21:30, 1 490 ₽');
});

test('НАХОДКА M4-8 (низкая): невидимые символы и разделители не из перечня обходят маску', () => {
  const bypass = [
    '+7​912​345​67​89', // пробел нулевой ширины — выглядит как +79123456789
    '+7­912­345­67­00', // мягкий перенос — не виден
    '+7⁠912⁠345⁠67⁠01', // word joiner — не виден
    '+7·912·345·67·96',
    '+7,912,345,67,97',
    '+7:912:345:67:98',
    '+7~912~345~67~99',
    '+7 ... 912 ... 345 ... 67 ... 95',
  ];
  const leaked = bypass.filter((s) => maskPhones(s) === s);
  for (const s of leaked) console.log(`  без маски: ${JSON.stringify(s)} (цифр: ${s.replace(/\D/g, '').length})`);
  // Утверждение «уязвимость есть»: после исправления этот тест должен упасть и быть переписан на «выдержало».
  assert.equal(leaked.length, bypass.length);
});
