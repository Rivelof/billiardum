const HHMM = /^\d{2}:\d{2}$/;

/** Коды, которые знает словарь (для тестов и подсказок разработчику). */
export const KNOWN_CODES = Object.freeze(Object.keys(TEXTS));

/**
 * Код ошибки из чего угодно: ApiError, строки, обычной ошибки.
 * @param {unknown} err
 * @returns {string}
 */
export function errorCode(err) {
  if (typeof err === 'string') return err;
  if (err && typeof err === 'object' && typeof err.code === 'string') return err.code;
  if (err instanceof TypeError) return 'network';
  return 'unknown';
}

/**
 * @param {unknown} err ApiError, код строкой или любая ошибка
 * @param {{ audience?: 'guest' | 'staff', busyUntil?: string, limitUntil?: string }} [ctx] busyUntil — уже отформатированное
 *   время клуба, '21:40'; limitUntil — extend_limit_until котировки в формате времени клуба, '20:55' (booking_conflict;
 *   у персонала — и limit_exceeded продления турнира)
 * @returns {{ code: string, title: string, action: string, text: string }}
 */
export function errorMessage(err, ctx = {}) {
  const audience = ctx.audience === 'staff' ? 'staff' : 'guest';
  const code = errorCode(err);
  const entry = TEXTS[code] ?? TEXTS.unknown;
  const [baseTitle, action] = Array.isArray(entry) ? entry : entry[audience];
  let title = baseTitle;
  // Стол турнира (light, M4): 409 table_busy { reason: 'tournament', busy_until }
  const tournament = code === 'table_busy' && err?.data?.reason === 'tournament';
  if (tournament) {
    title = ctx.busyUntil ? `Стол занят турниром до ${ctx.busyUntil}.` : 'Стол занят турниром.';
    return { code, title, action: 'Выберите другой стол или приходите после турнира.', text: `${title} Выберите другой стол или приходите после турнира.` };
  }
  if (code === 'table_busy' && ctx.busyUntil) title = `Стол занят до ${ctx.busyUntil}.`;
  // M5.1: 400 tariff_gap | tariff_overlap { weekday, from, to } — где именно дыра или пересечение (местное время клуба)
  if ((code === 'tariff_gap' || code === 'tariff_overlap') && ON_WEEKDAY[err?.data?.weekday]) {
    const d = err.data;
    const span = HHMM.test(d.from ?? '') && HHMM.test(d.to ?? '') ? ` с ${d.from} до ${d.to}` : '';
    const day = ON_WEEKDAY[d.weekday];
    title = `${day[0].toUpperCase()}${day.slice(1)}${span} ${code === 'tariff_gap' ? 'нет цены' : 'задано две цены'}.`;
  }
  if (code === 'booking_conflict' && ctx.limitUntil) title = `Стол забронирован — можно продлить до ${ctx.limitUntil}.`;
  // Продление турнира (№147): 409 limit_exceeded { extend_limit_until } — предел в формате времени клуба
  if (code === 'limit_exceeded' && audience === 'staff' && ctx.limitUntil) {
    title = `Так далеко продлить нельзя: не позже ${ctx.limitUntil}.`;
    return { code, title, action: 'Выберите время не позже этого.', text: `${title} Выберите время не позже этого.` };
  }
  return { code, title, action, text: `${title} ${action}` };
}
