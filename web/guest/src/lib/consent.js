/**
 * Тексты шага согласия (152‑ФЗ) по сценарию: оплата стола, присоединение к чужой игре, очередь, бронь.
 * Гость, который присоединяется к игре, ничего не платит — про оплату ему не пишем (U2).
 * @param {'start' | 'join' | 'waitlist' | 'book' | string | undefined} intent
 * @returns {{ why: string, cta: string, required: string }}
 */
export function consentCopy(intent) {
  if (intent === 'join') {
    return {
      why: 'Мы храним номер телефона и историю игр на серверах в России. Они нужны для игры за столом: продлевать её со своего телефона, получать напоминания о конце и видеть партии в своей истории.',
      cta: 'Присоединиться к игре',
      required: 'Отметьте флажок: без согласия присоединиться к игре нельзя.',
    };
  }
  if (intent === 'waitlist') {
    return {
      why: 'Мы храним номер телефона на серверах в России. Он нужен, чтобы сообщить, когда стол освободится.',
      cta: 'Встать в очередь',
      required: 'Отметьте флажок: без согласия встать в очередь нельзя.',
    };
  }
  if (intent === 'book') {
    return {
      why: 'Мы храним номер телефона и брони на серверах в России. Они нужны для брони, чеков и напоминаний.',
      cta: 'Продолжить бронь',
      required: 'Отметьте флажок: без согласия бронь недоступна.',
    };
  }
  return {
    why: 'Мы храним номер телефона и историю игр на серверах в России. Они нужны для оплаты, чеков и напоминаний о конце игры.',
    cta: 'Продолжить к оплате',
    required: 'Отметьте флажок: без согласия оплата недоступна.',
  };
}

/** Заголовок входа на столе по сценарию: присоединение и очередь — не «оплатить». */
export function signInTitle(intent) {
  if (intent === 'join') return 'Войдите, чтобы присоединиться к игре';
  if (intent === 'waitlist') return 'Войдите, чтобы встать в очередь';
  return 'Войдите, чтобы оплатить';
}
