-- Сид разработки backend-light (контракт M1 §13): фиксированные коды 8 столов тестового
-- клуба, чтобы tester и frontend открывали /api/t/{code} и /app/t/{code} без поиска в базе.
-- Только разработка (decisions №21): в проде коды случайные (bl.gen_resource_code, №47).
-- Алфавит Crockford Base32 без I, L, O, U. Повторный запуск ничего не меняет.

update bl.resources r
   set code = v.code
  from (values
    ('e1000000-0000-4000-8000-000000000001'::uuid, 'TEST000001'),
    ('e1000000-0000-4000-8000-000000000002'::uuid, 'TEST000002'),
    ('e1000000-0000-4000-8000-000000000003'::uuid, 'TEST000003'),
    ('e1000000-0000-4000-8000-000000000004'::uuid, 'TEST000004'),
    ('e1000000-0000-4000-8000-000000000005'::uuid, 'TEST000005'),
    ('e1000000-0000-4000-8000-000000000006'::uuid, 'TEST000006'),
    ('e1000000-0000-4000-8000-000000000007'::uuid, 'TEST000007'),
    ('e1000000-0000-4000-8000-000000000008'::uuid, 'TEST000008')
  ) as v (id, code)
 where r.id = v.id and r.code is distinct from v.code;
