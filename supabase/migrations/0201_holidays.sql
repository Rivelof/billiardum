-- 0201: нерабочие праздничные и перенесённые дни производственного календаря РФ (decisions №43).
--
-- Праздник считается выходным при выборе тарифа (server/tariffs/, holiday_iso_day клуба).
-- club_id NULL — федеральный календарь (виден всем клубам); строка с club_id — свой день
-- клуба (региональный праздник), видна только этому клубу. Рабочие субботы не хранятся:
-- тариф берётся по дню недели.
--
-- Источники:
--   * ст. 112 Трудового кодекса РФ — нерабочие праздничные дни: 1–6 и 8 января (новогодние
--     каникулы), 7 января, 23 февраля, 8 марта, 1 мая, 9 мая, 12 июня, 4 ноября; выходной,
--     совпавший с праздником (кроме январских), переносится на следующий рабочий день;
--   * постановление Правительства РФ от 24.09.2025 № 1466 «О переносе выходных дней в 2026 году»:
--     суббота 3 января → пятница 9 января, воскресенье 4 января → четверг 31 декабря;
--   * постановление Правительства РФ от 17.09.2026 № 1187 «О переносе выходных дней в 2027 году»
--     (http://government.ru/docs/59913/, https://www.garant.ru/hotlaw/federal/2245207/):
--     суббота 2 января → пятница 5 ноября, воскресенье 3 января → пятница 31 декабря,
--     суббота 20 февраля → понедельник 22 февраля.
-- Следующий год — новой миграцией после выхода постановления (обычно в сентябре).

create table bl.holidays (
  id uuid primary key default gen_random_uuid(),
  club_id uuid references bl.clubs (id),
  day date not null,
  kind text not null check (kind in ('holiday', 'transfer')),
  title text not null check (length(title) between 1 and 200),
  created_at timestamptz not null default now(),
  constraint holidays_club_day unique nulls not distinct (club_id, day)
);
create index holidays_day_idx on bl.holidays (day);

comment on table bl.holidays is 'Нерабочие дни: праздники ст. 112 ТК РФ и переносы по постановлениям Правительства (club_id NULL), свои дни клуба (club_id).';

alter table bl.holidays owner to bl_owner;
alter table bl.holidays enable row level security;
alter table bl.holidays force row level security;

create policy holidays_app_select on bl.holidays for select to app_api
  using (club_id is null or club_id = bl.ctx_club_id());

revoke all on bl.holidays from public;
grant select on bl.holidays to app_api;

